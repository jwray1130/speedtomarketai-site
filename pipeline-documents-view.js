  function sanitizeHtml(html) {
    if (typeof html !== 'string' || !html) return html;
    try {
      // DOMParser creates an inert document — no script execution, no
      // network fetch during parse. The allowlist walk below strips
      // anything not explicitly permitted.
      const doc = new DOMParser().parseFromString('<div id="__root__">' + html + '</div>', 'text/html');
      const root = doc.getElementById('__root__');
      if (!root) return '';

      const walk = (el) => {
        const children = Array.from(el.children);
        for (const child of children) {
          const tag = (child.tagName || '').toLowerCase();
          if (!DOCS_VIEW_SAFE_TAGS.has(tag)) {
            child.remove();
            continue;
          }
          const attrs = Array.from(child.attributes);
          for (const attr of attrs) {
            const name = attr.name.toLowerCase();
            // Always strip event handlers (onclick, onerror, onload, etc.)
            if (name.startsWith('on')) { child.removeAttribute(attr.name); continue; }
            // Style attributes can hide expressions like background:url(javascript:)
            if (name === 'style') { child.removeAttribute(attr.name); continue; }
            // srcset can carry external URLs — strip
            if (name === 'srcset') { child.removeAttribute(attr.name); continue; }
            // <a href> — only allow safe protocols (http/https/mailto/tel/relative)
            if (tag === 'a' && name === 'href') {
              const v = (attr.value || '').trim().toLowerCase();
              const safe = v.startsWith('http://') || v.startsWith('https://') ||
                           v.startsWith('mailto:') || v.startsWith('tel:') ||
                           v.startsWith('/') || v.startsWith('#') || v.startsWith('?');
              if (!safe) { child.removeAttribute(attr.name); continue; }
              if (v.startsWith('http://') || v.startsWith('https://')) {
                child.setAttribute('target', '_blank');
                child.setAttribute('rel', 'noopener noreferrer');
              }
              continue;
            }
            // <img src> — only allow data:image/* URIs (mammoth output) and
            // safe http(s)/relative URLs. javascript:/vbscript: blocked.
            if (tag === 'img' && name === 'src') {
              const v = (attr.value || '').trim().toLowerCase();
              const safe = /^data:image\/(png|jpeg|gif|webp|bmp);base64,/i.test(v);if(!safe){const label=document.createElement('span');label.textContent=child.getAttribute('alt')||'[External image omitted]';child.replaceWith(label);break;}
              if (!safe) { child.removeAttribute(attr.name); continue; }
              continue;
            }
            // Any other attribute not on the allowlist → drop
            if (!DOCS_VIEW_SAFE_ATTRS.has(name)) { child.removeAttribute(attr.name); continue; }
            // Final defense: strip javascript:/vbscript: from any remaining attribute
            if (typeof attr.value === 'string' && /(?:javascript|vbscript)\s*:/i.test(attr.value)) {
              child.removeAttribute(attr.name);
            }
          }
          walk(child);
        }
      };
      walk(root);
      return root.innerHTML;
    } catch (e) {
      console.warn('docs-view sanitizeHtml failed, returning escaped fallback', e);
      // Fallback: render as escaped text so worst case is "ugly card" not "XSS"
      return (html || '').replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
    }
  }

  // ════════════════════════════════════════════════════════════════════
  // v8.6: PER-PAGE TAG RESOLUTION FOR COMBINED PDFs
  //
  // For combined PDFs (e.g. combined package app = ACORD 125 + ACORD 126 +
  // ACORD 131), pctx.sectionClassifications contains per-section tags +
  // section_hint page ranges. _resolvePerPageTag finds which section a
  // given page belongs to and returns its tag if the page is the section's
  // first page (so each section gets exactly one chip on its starting
  // page, not on every page).
  //
  // Rules:
  //   1. If pctx.sectionClassifications is present:
  //      - Page is the start of a section → return that section's tag
  //      - Page is mid-section → return null (no chip)
  //   2. Fall back to legacy first-page-only behavior if no
  //      sectionClassifications provided (single-section docs).
  // ════════════════════════════════════════════════════════════════════
  function _parsePageRangeForChip(hint, totalPages) {
    if (!hint || typeof hint !== 'string') return null;
    const h = hint.toLowerCase().trim();
    if (h === 'entire document' || h === 'all pages' || h === 'all') {
      return [1, totalPages || 1];
    }
    const m = h.match(/(?:pages?|p\.?)\s*(\d+)\s*(?:[-–—\sto]+\s*(\d+))?/);
    if (!m) return null;
    const start = parseInt(m[1], 10);
    const end = m[2] ? parseInt(m[2], 10) : start;
    return [start, end];
  }
  function _resolvePerPageTag(opts, pctx) {
    const pageNum = opts.pageNumber || 1;
    // v8.6.7: prefer pctx.sectionClassifications (pipeline-driven path),
    // fall back to opts.sectionClassifications (direct caller path).
    // Either source yields the same shape: array of {tag, section_hint, ...}.
    const sections =
      (pctx && Array.isArray(pctx.sectionClassifications) && pctx.sectionClassifications) ||
      (opts && Array.isArray(opts.sectionClassifications) && opts.sectionClassifications) ||
      null;
    if (Array.isArray(sections) && sections.length > 0) {
      // Find a section whose range STARTS at this page
      for (const s of sections) {
        const range = _parsePageRangeForChip(s.section_hint, opts.totalPages);
        if (range && range[0] === pageNum) {
          return s.tag || null;
        }
      }
      // No section starts at this exact page → no chip
      return null;
    }
    // Legacy single-classification path: chip on page 1 only
    if (pageNum === 1) return opts.pipelineTag || (pctx && pctx.pipelineTag) || null;
    return null;
  }

