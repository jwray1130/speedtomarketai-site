  // Called by app.js showStage('docs') — runs every time the docs view
  // becomes visible. Re-measures Word-thumb CSS scale and resizes
  // annotation canvases so they pick up any container size changes that
  // happened while the view was hidden.
  window.docsViewActivated = function() {
    document.querySelectorAll('#docs-view-root .doc-thumb-word').forEach(wrap => {
      const page = wrap.querySelector('.doc-thumb-word-page');
      if (page && wrap.clientWidth > 0) {
        page.style.transform = 'scale(' + (wrap.clientWidth / 816) + ')';
      }
    });
    if (window.__docsAnno && typeof window.__docsAnno.ensureCanvas === 'function') {
      document.querySelectorAll('#docs-view-root .anno-canvas-wrap').forEach(wrap => {
        const thumb = wrap.parentElement;
        const docId = wrap.dataset.docId;
        if (thumb && docId) window.__docsAnno.ensureCanvas(thumb, docId);
      });
    }
    // v8.6.25: thumbnail enrichment is now deferred while the docs view is
    // hidden, so kick it when the user actually opens Documents. It is
    // idempotent and self-guards if another enrichment run is active.
    try {
      const sid = state.submissionFilter !== 'all' ? state.submissionFilter : state.activeSubmissionId;
      scheduleLazyEnrichment(sid || null);
    } catch (e) {}
  };
