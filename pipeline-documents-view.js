  // ══════ FILTER / SORT / RENDER DOC LIST ══════
  function filterDocs() {
    let docs = [...state.docs];
    // Submission scope filter applied first so all subsequent counters
    // (search hit totals, category counts) reflect the scoped set.
    if (state.draftSubmissionMode && window.docsView?.design) { docs=docs.filter(inDesignScope); }
    else if (state.submissionFilter && state.submissionFilter !== 'all') {
      docs = docs.filter(d => d.submissionId === state.submissionFilter);
    }
    if (state.currentCategory !== 'all') {
      docs = docs.filter(d => d.category === state.currentCategory);
    }
    if (state.searchQuery) {
      const q = state.searchQuery.toLowerCase();
      const qEscaped = q.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
      const re = new RegExp(qEscaped, 'gi');
      let total = 0;
      docs = docs.filter(d => {
        const name = (d.displayName || '');
        const text = (d.textContent || '');
        const nameHits = (name.match(re) || []).length;
        const textHits = (text.match(re) || []).length;
        const hits = nameHits + textHits;
        if (hits > 0) {
          d._searchMatches = hits;
          total += hits;
          return true;
        }
        delete d._searchMatches;
        return false;
      });
      state.searchTotalMatches = total;
    } else {
      state.docs.forEach(d => { delete d._searchMatches; });
      state.searchTotalMatches = 0;
    }
    const sorted = sortDocs(docs);
    // Keep searchResults in sync with current filtered + sorted state
    if (state.searchQuery) {
      state.searchResults = sorted.map(d => d.id);
    } else {
      state.searchResults = [];
    }
    return sorted;
  }

