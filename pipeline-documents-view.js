  function toggleTheme() {
    // Delegate to Altitude's theme toggle if available — this keeps the
    // host app and the docs view in sync (both watch html[data-theme]).
    if (typeof window.toggleTheme === 'function' && window.toggleTheme !== toggleTheme) {
      window.toggleTheme();
      return;
    }
    // Fallback: local toggle (only happens if Altitude's toggle isn't
    // exposed yet, e.g. very early in boot).
    const current = document.documentElement.getAttribute('data-theme') === 'light' ? 'light' : 'dark';
    const next = current === 'dark' ? 'light' : 'dark';
    if (next === 'light') document.documentElement.setAttribute('data-theme', 'light');
    else document.documentElement.removeAttribute('data-theme');
  }

